package core.world;

/**
 * 形状对 **贴图 UV** 的影响 —— 纯函数、无状态、零 RNG、<b>不进 hashState</b>。
 *
 * <p><b>它解决什么</b>（第二十批）：顶点被形状收窄之后，贴图却仍按**整格的 UV** 采样 ⇒
 * 半砖的侧面贴图会被<b>压扁</b>到半格高（砖纹变扁、石纹变密）。正确做法是让 UV 跟着实心区间走：
 * 侧壁只采样贴图里对应的那一段。
 *
 * <p><b>为什么放在 {@code core} 而不是渲染层</b>（与 {@link FaceCull} 完全同一条理由）：
 * 规则进 core 才能被 {@code core.sim} 的无头门禁守护；而渲染层里的 UV 数学够不着任何门禁 ——
 * 于是这类改动会退化成"看起来对就行"（本项目最不想要的那种东西）。
 * 放进 core 还有第二个好处：<b>不透明满格世界下它退化为恒等函数</b> ⇒ 逐字节等价改动前。
 *
 * <p>⚠️ <b>顶面 / 底面不调用本类</b>：从上看或下看时贴图本就该完整，压缩反而是错的。
 * 只有侧壁（法线为水平的那些面）需要它 —— 调用点的判据就是"法线的 y 分量 == 0"。
 */
public final class ShapeUV {

    private ShapeUV() { }

    /**
     * 侧壁（±X / ±Z 面）上**一条竖直 UV 分量**的映射。
     *
     * <p>{@code cv} 是面的局部竖直参数（0 = 该面下沿、1 = 该面上沿）。语义是
     * "**把整张贴图竖直方向的比例，映射到实心区间占整格的比例**"：
     * <ul>
     *   <li>满格 {@code (0,1)} → 原样返回（**零回归的落点**）；</li>
     *   <li>下半砖 {@code (0,0.5)} → {@code cv·0.5} ⇒ 只取贴图**下半段**（不再压扁）；</li>
     *   <li>上半砖 {@code (0.5,0.5)} → {@code 0.5 + cv·0.5} ⇒ 取**上半段**；</li>
     *   <li>雪层 {@code (0,0.125)} → {@code cv·0.125} ⇒ 只取最底一条；</li>
     *   <li>台阶：形状记 {@code (0,1)}（L 形不是"矮"）⇒ <b>原样返回</b> —— 它的侧壁本就该完整。</li>
     * </ul>
     * 最后一条正是"用 {@code (base,height)} 表达形状"的红利：台阶不被误当成矮块。
     */
    public static float sideV(Blocks.Block blk, float cv) {
        if (blk == null || blk.isFullShape()) return cv;
        return blk.shapeBase + cv * blk.shapeHeight;
    }
}
